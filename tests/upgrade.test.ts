/**
 * Tests for ai-gov upgrade command.
 * Verifies: hooks regenerated, steering preserved by default,
 * steering overwritten with --force, app name preserved from CLAUDE.md,
 * dry-run writes nothing, cross-platform chmod safety.
 */
import { mkdirSync, writeFileSync, existsSync, readFileSync } from 'fs';
import { join } from 'path';
import { tmpdir } from 'os';
import { runUpgrade } from '../src/commands/upgrade.js';

// ---------------------------------------------------------------------------
// Helpers
// ---------------------------------------------------------------------------

function makeTmpDir(prefix: string): string {
    const dir = join(tmpdir(), `ai-gov-upgrade-${prefix}-${Date.now()}`);
    mkdirSync(dir, { recursive: true });
    return dir;
}

/**
 * Creates a minimal project that looks like it was previously initialised by
 * ai-gov init — has .claude/ with hooks/, git-hooks/, commands/, steering/.
 */
function makeInitialisedProject(dir: string, appName = 'MyExistingApp'): void {
    writeFileSync(join(dir, 'package.json'), JSON.stringify({
        name: 'test-app',
        version: '1.0.0',
        dependencies: { react: '^18.0.0' },
    }, null, 2));

    const claudeDir = join(dir, '.claude');
    mkdirSync(join(claudeDir, 'hooks'),     { recursive: true });
    mkdirSync(join(claudeDir, 'commands'),  { recursive: true });
    mkdirSync(join(claudeDir, 'git-hooks'), { recursive: true });
    mkdirSync(join(claudeDir, 'steering'),  { recursive: true });

    // CLAUDE.md with embedded app name (format generated by ai-gov)
    writeFileSync(join(claudeDir, 'CLAUDE.md'),
        `# AI Governance\n\n**App:** ${appName} — A test application\n\n## Rules\n`);

    // Old / placeholder hook files (upgrade should replace these)
    writeFileSync(join(claudeDir, 'hooks', 'check-secrets.sh'),
        '#!/bin/bash\n# PLACEHOLDER OLD VERSION\nexit 0\n');
    writeFileSync(join(claudeDir, 'hooks', 'protect-files.sh'),
        '#!/bin/bash\n# PLACEHOLDER OLD VERSION\nexit 0\n');

    // Steering files with team-specific content (upgrade must NOT touch these by default)
    writeFileSync(join(claudeDir, 'steering', 'architecture.md'),
        '# Team Architecture\nCustom content — DO NOT OVERWRITE.\n');
    writeFileSync(join(claudeDir, 'steering', 'coding-standards.md'),
        '# Team Standards\nCustom standards — DO NOT OVERWRITE.\n');
    writeFileSync(join(claudeDir, 'steering', 'workflow.md'),
        '# Team Workflow\nCustom workflow — DO NOT OVERWRITE.\n');
    writeFileSync(join(claudeDir, 'steering', 'constitution.md'),
        '# Team Constitution\nCustom constitution — DO NOT OVERWRITE.\n');
}

// ---------------------------------------------------------------------------
// Suite: hook regeneration
// ---------------------------------------------------------------------------

describe('upgrade — hook regeneration', () => {
    let projectDir: string;

    beforeAll(() => {
        projectDir = makeTmpDir('hooks');
        makeInitialisedProject(projectDir);
        runUpgrade({ dir: projectDir, force: false, dryRun: false });
    });

    test('replaces stale Claude Code hooks', () => {
        const secretsHook = readFileSync(
            join(projectDir, '.claude', 'hooks', 'check-secrets.sh'), 'utf-8',
        );
        // Old placeholder content must be gone; real hook content present
        expect(secretsHook).not.toContain('PLACEHOLDER OLD VERSION');
        expect(secretsHook).toContain('#!/usr/bin/env bash');
    });

    test('generates all expected hook files', () => {
        const hooks = [
            'check-secrets.sh', 'protect-files.sh', 'block-dangerous-commands.sh',
            'check-spec-exists.sh', 'session-continuity.sh', 'format-code.sh',
            'analyze-code.sh', 'check-feature-readme.sh', 'check-consistency.sh',
            'check-file-size.sh', 'post-task-checklist.sh',
        ];
        for (const h of hooks) {
            expect(existsSync(join(projectDir, '.claude', 'hooks', h))).toBe(true);
        }
    });

    test('regenerates git-hook scripts', () => {
        expect(existsSync(join(projectDir, '.claude', 'git-hooks', 'pre-commit.sh'))).toBe(true);
        expect(existsSync(join(projectDir, '.claude', 'git-hooks', 'checks', 'secrets.sh'))).toBe(true);
        expect(existsSync(join(projectDir, '.claude', 'git-hooks', 'checks', 'file-size.sh'))).toBe(true);
    });

    test('regenerates slash commands', () => {
        const commands = ['audit.md', 'new-feature.md', 'edit-feature.md', 'fix.md',
            'refactor.md', 'hotfix.md', 'explore.md', 'jira.md', 'backlog.md'];
        for (const c of commands) {
            expect(existsSync(join(projectDir, '.claude', 'commands', c))).toBe(true);
        }
    });

    test('regenerates .claude/CLAUDE.md', () => {
        const content = readFileSync(join(projectDir, '.claude', 'CLAUDE.md'), 'utf-8');
        expect(content.length).toBeGreaterThan(100);
        expect(content).toContain('##'); // has sections
    });

    test('jira.md command generated on upgrade', () => {
        expect(existsSync(join(projectDir, '.claude', 'commands', 'jira.md'))).toBe(true);
        const content = readFileSync(join(projectDir, '.claude', 'commands', 'jira.md'), 'utf-8');
        expect(content.startsWith('# /jira')).toBe(true);
        expect(content).toContain('jira_get');
    });

    test('generated hooks use python3/jq dual runtime (no jq-only guard)', () => {
        const hook = readFileSync(join(projectDir, '.claude', 'hooks', 'check-secrets.sh'), 'utf-8');
        expect(hook).not.toContain('command -v jq &>/dev/null || exit 0');
        expect(hook).toContain('python3');
    });
});

