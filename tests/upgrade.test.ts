describe('upgrade --force — steering overwrite', () => {
    let projectDir: string;

    beforeAll(() => {
        projectDir = makeTmpDir('force');
        makeInitialisedProject(projectDir);
        runUpgrade({ dir: projectDir, force: true, dryRun: false });
    });

    test('overwrites architecture.md with generated content', () => {
        const content = readFileSync(
            join(projectDir, '.claude', 'steering', 'architecture.md'), 'utf-8',
        );
        // Generated content replaces the placeholder
        expect(content).not.toContain('DO NOT OVERWRITE');
        expect(content.length).toBeGreaterThan(50);
    });

    test('overwrites coding-standards.md with generated content', () => {
        const content = readFileSync(
            join(projectDir, '.claude', 'steering', 'coding-standards.md'), 'utf-8',
        );
        expect(content).not.toContain('DO NOT OVERWRITE');
    });

    test('generates task-estimates.md in steering under --force', () => {
        expect(existsSync(join(projectDir, '.claude', 'steering', 'task-estimates.md'))).toBe(true);
        const content = readFileSync(join(projectDir, '.claude', 'steering', 'task-estimates.md'), 'utf-8');
        expect(content).toContain('[~');
        expect(content).toContain('[S]');
    });
});

// ---------------------------------------------------------------------------
// Suite: app name preserved from existing CLAUDE.md
// ---------------------------------------------------------------------------

describe('upgrade — app name preservation', () => {
    test('reads app name from existing .claude/CLAUDE.md', () => {
        const projectDir = makeTmpDir('appname');
        makeInitialisedProject(projectDir, 'AcmePaymentService');
        runUpgrade({ dir: projectDir, force: false, dryRun: false });

        const newClaudeMd = readFileSync(join(projectDir, '.claude', 'CLAUDE.md'), 'utf-8');
        expect(newClaudeMd).toContain('AcmePaymentService');
    });

    test('falls back to package.json name when CLAUDE.md has no app name', () => {
        const projectDir = makeTmpDir('pkgname');
        writeFileSync(join(projectDir, 'package.json'), JSON.stringify({
            name: 'my-pkg-app', version: '1.0.0',
        }, null, 2));
        const claudeDir = join(projectDir, '.claude');
        mkdirSync(join(claudeDir, 'hooks'),     { recursive: true });
        mkdirSync(join(claudeDir, 'commands'),  { recursive: true });
        mkdirSync(join(claudeDir, 'git-hooks'), { recursive: true });
        mkdirSync(join(claudeDir, 'steering'),  { recursive: true });
        // CLAUDE.md with no **App:** line
        writeFileSync(join(claudeDir, 'CLAUDE.md'), '# Governance\nNo app name here.\n');

        runUpgrade({ dir: projectDir, force: false, dryRun: false });

        const newClaudeMd = readFileSync(join(claudeDir, 'CLAUDE.md'), 'utf-8');
        expect(newClaudeMd).toContain('my-pkg-app');
    });
});

// ---------------------------------------------------------------------------
// Suite: dry-run
// ---------------------------------------------------------------------------

describe('upgrade --dry-run', () => {
    test('does not modify hook files', () => {
        const projectDir = makeTmpDir('dryrun');
        makeInitialisedProject(projectDir);

        const sentinel = '#!/bin/bash\n# SENTINEL — must not change\nexit 0\n';
        writeFileSync(join(projectDir, '.claude', 'hooks', 'check-secrets.sh'), sentinel);

        runUpgrade({ dir: projectDir, force: false, dryRun: true });

        const content = readFileSync(
            join(projectDir, '.claude', 'hooks', 'check-secrets.sh'), 'utf-8',
        );
        expect(content).toBe(sentinel);
    });

    test('does not create new git-hook files', () => {
        const projectDir = makeTmpDir('dryrun2');
        makeInitialisedProject(projectDir);

        // Ensure no git-hooks exist initially beyond the empty dir
        const preCommit = join(projectDir, '.claude', 'git-hooks', 'pre-commit.sh');
        expect(existsSync(preCommit)).toBe(false);

        runUpgrade({ dir: projectDir, force: false, dryRun: true });

        expect(existsSync(preCommit)).toBe(false);
    });
});
